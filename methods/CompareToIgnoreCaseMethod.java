
// Comapre to IgnoreCase Method
package strings.methods;
public class CompareToIgnoreCaseMethod {
	public static void main(String[] args) {
		System.out.println("java".compareToIgnoreCase("Java"));
		System.out.println("python".compareToIgnoreCase("PYTHON"));
		System.out.println("cat".compareToIgnoreCase("dog"));
		System.out.println("java".compareToIgnoreCase("FULL"));
		System.out.println("FULL".compareToIgnoreCase("FULL"));
		System.out.println("lion".compareToIgnoreCase("LION"));
	

	}

}
