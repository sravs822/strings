
// repeat() - Repeats the string a specified number of times.
package strings.methods;
public class RepeatMethod {
	public static void main(String[] args) {
		System.out.println("*".repeat(100));
		System.out.println("=".repeat(100));
		System.out.println("Hi".repeat(50));
		System.out.println("*".repeat(100));
	}

}
