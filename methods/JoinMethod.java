
// join() - Joins multiple strings using a specified delimiter (separator).
package strings.methods;
public class JoinMethod {
	public static void main(String[] args) {
		System.out.println(String.join("-","Java","Python","SQL"));
		System.out.println(String.join("@","Sravanthi","gmail.com"));
		System.out.println(String.join("/","21","10","2004"));
	}

}
