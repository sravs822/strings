
// concat() - Joins (concatenates) two strings and returns a new string.
package strings.methods;
public class ConcatMethod {
	public static void main(String[] args) {
		String s="Java";
		String s2="FullStack";
		System.out.println(s2);
		System.out.println("Hello".concat(" World"));
		System.out.println("Programming".concat("Language"));
		System.out.println(s+"  Introduced in th year "+1996);
	}

}
